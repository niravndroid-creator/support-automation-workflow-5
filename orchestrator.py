def run_workflow(input_data: dict) -> dict:
    """Execute: Support-mailbox-automation"""
    logger.info("Workflow started: Support-mailbox-automation")
    _step_logs.clear()
    data = dict(input_data)
    try:
        data = step_get_unread_emails(data)
        # For-each: For each unread emails
        _for_each_unread_emails_items = _get_items_for_each_unread_emails(data)
        logger.info(f"For-each 'For each unread emails': {len(_for_each_unread_emails_items)} item(s)")
        _for_each_unread_emails_results = []
        for item in _for_each_unread_emails_items:
            data["item"] = item
            data = step_get_email_detail(data)
            data = step_determine_the_email_intent(data)
            if _condition_is_email_about_tracking_order(data):  # Is Email about Tracking Order
                data = step_respond_email(data)
            _for_each_unread_emails_results.append(data.copy())
        data["for_each_unread_emails_results"] = _for_each_unread_emails_results

        logger.info("Workflow completed: Support-mailbox-automation")
        return data
    except Exception as exc:
        logger.error(f"Workflow failed: {exc}", exc_info=True)
        raise

