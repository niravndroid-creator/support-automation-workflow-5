def _get_items_for_each_unread_emails(data: dict) -> list:
    """Resolve iteration list for: For each unread emails"""
    try:
        mcp_result = data.get("get_unread_emails_result", [])
        if not isinstance(mcp_result, dict):
            return mcp_result if isinstance(mcp_result, list) else ([mcp_result] if mcp_result is not None else [])
        # Extract records from MCP structuredContent.result
        items = mcp_result.get("structuredContent", {}).get("result", [])
        if items:
            return items
        # Fallback: parse content[0].text if structuredContent missing
        content_text = (mcp_result.get("content") or [{}])[0].get("text", "")
        if content_text:
            parsed = json.loads(content_text)
            return parsed if isinstance(parsed, list) else [parsed]
        return []
    except Exception as exc:
        logger.error(f"For-each 'For each unread emails' list error: {exc}")
        return []

