def run(input_data: dict | None = None) -> dict:
    """
    Execute 'Support-mailbox-automation' with optional input.
    Called by the timer and HTTP triggers in function_app.py.
    Also usable directly:  from orchestrator import run; run()
    """
    from datetime import datetime, timezone
    started_at = datetime.now(timezone.utc).isoformat()
    instance_id = datetime.now(timezone.utc).strftime("%Y-%m-%d:%H-%M-%S")
    date_part = instance_id[:10]
    container = _get_cosmos_container()
    status = "success"
    try:
        result = run_workflow(input_data or {})
        logger.info("Workflow completed: %s", json.dumps(result, default=str)[:300])
        return result
    except Exception as exc:
        status = "error"
        logger.error("Workflow failed: %s", exc, exc_info=True)
        raise
    finally:
        _flush_to_cosmos(container, instance_id, date_part, started_at, status, get_step_logs())


