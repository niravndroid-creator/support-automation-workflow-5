def _get_cosmos_container():
    """Return the Cosmos DB container for execution tracing, or None."""
    from workflow_config import COSMOS_DB_ENDPOINT, COSMOS_DB_DATABASE, COSMOS_DB_KEY, WORKFLOW_ID
    if not (COSMOS_DB_ENDPOINT and COSMOS_DB_DATABASE and COSMOS_DB_KEY and WORKFLOW_ID):
        return None
    try:
        from azure.cosmos import CosmosClient, PartitionKey
        client = CosmosClient(url=COSMOS_DB_ENDPOINT, credential=COSMOS_DB_KEY)
        db = client.get_database_client(COSMOS_DB_DATABASE)
        return db.create_container_if_not_exists(
            id=WORKFLOW_ID,
            partition_key=PartitionKey(path="/date"),
        )
    except Exception as exc:
        logger.warning("Cosmos DB container init failed: %s", exc)
        return None


def _flush_to_cosmos(container, instance_id: str, date_part: str, started_at: str, status: str, step_logs: list) -> None:
    if container is None:
        return
    from datetime import datetime, timezone
    from workflow_config import WORKFLOW_ID, WORKFLOW_NAME
    try:
        doc = {
            "id": instance_id,
            "date": date_part,
            "workflowId": WORKFLOW_ID,
            "workflowName": WORKFLOW_NAME,
            "instanceId": instance_id,
            "startedAt": started_at,
            "completedAt": datetime.now(timezone.utc).isoformat(),
            "status": status,
            "logs": step_logs,
        }
        container.upsert_item(doc)
    except Exception as exc:
        logger.warning("Cosmos DB flush failed: %s", exc)


