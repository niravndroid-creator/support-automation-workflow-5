def _run_agent(agent_id: str, agent_version: str, data: dict) -> dict:
    """Call a pre-deployed Azure AI Foundry agent via AIProjectClient SDK."""
    # Build input — send only the current item context, not the entire data blob
    input_messages = [{"role": "user", "content": json.dumps(data, default=str)}]
    agent_reference = {"name": agent_id, "version": agent_version, "type": "agent_reference"}

    logger.info("=" * 60)
    logger.info(f"AI AGENT REQUEST  [{agent_id}  v{agent_version}]")
    logger.info(f"  Endpoint       : {PROJECT_ENDPOINT}")
    logger.info(f"  Agent reference: {json.dumps(agent_reference)}")
    logger.info(f"  Input messages :\n{json.dumps(input_messages, indent=4, default=str)}")
    logger.info("=" * 60)

    # api_key= MUST be passed explicitly — without it get_openai_client()
    # calls get_bearer_token_provider() which fails for AzureKeyCredential.
    openai_client = _project_client.get_openai_client(api_key=AZURE_AI_API_KEY)
    response = openai_client.responses.create(
        input=input_messages,
        extra_body={"agent_reference": agent_reference},
    )
    response_text = response.output_text

    logger.info("=" * 60)
    logger.info(f"AI AGENT RESPONSE [{agent_id}  v{agent_version}]")
    logger.info(f"  Content:\n{response_text}")
    logger.info("=" * 60)

    try:
        parsed = json.loads(response_text)
        if isinstance(parsed, list) and parsed:
            parsed = parsed[0]  # agent returns a list — take first item
        if isinstance(parsed, dict):
            return {**data, **parsed}
        return {**data, "agent_output": parsed}
    except json.JSONDecodeError:
        return {**data, "agent_output": response_text}

# MCP Streamable HTTP transport — required Accept header to avoid 406 responses
_MCP_HEADERS = {
    "Content-Type": "application/json",
    "Accept": "application/json, text/event-stream",
}

def _mcp_post(server_endpoint: str, payload: dict, session_id: str | None = None):
    """POST a JSON-RPC message to an MCP server; handle both JSON and SSE responses."""
    headers = dict(_MCP_HEADERS)
    if session_id:
        headers["Mcp-Session-Id"] = session_id
    response = requests.post(server_endpoint, json=payload, headers=headers, timeout=30)
    response.raise_for_status()
    returned_session_id = response.headers.get("Mcp-Session-Id")
    content_type = response.headers.get("Content-Type", "")
    if "text/event-stream" in content_type:
        for line in response.text.splitlines():
            if line.startswith("data:"):
                data = line[len("data:"):].strip()
                if data and data != "[DONE]":
                    return json.loads(data), returned_session_id
        return {}, returned_session_id
    body = response.json() if response.content else {}
    return body, returned_session_id

def _call_mcp_tool(server_endpoint: str, tool_name: str, args: dict) -> dict:
    """Call an MCP server tool using the full Streamable HTTP 3-step handshake."""
    # Step 1: Initialize — server returns Mcp-Session-Id header
    init_payload = {
        "jsonrpc": "2.0", "id": 0,
        "method": "initialize",
        "params": {
            "protocolVersion": "2024-11-05",
            "capabilities": {},
            "clientInfo": {"name": "workflow-client", "version": "1.0"},
        },
    }
    _, session_id = _mcp_post(server_endpoint, init_payload)
    # Step 2: Send initialized notification (fire-and-forget)
    notif = {"jsonrpc": "2.0", "method": "notifications/initialized", "params": {}}
    try:
        _mcp_post(server_endpoint, notif, session_id)
    except Exception:
        pass
    # Step 3: Call the tool
    payload = {
        "jsonrpc": "2.0", "id": 1,
        "method": "tools/call",
        "params": {"name": tool_name, "arguments": args},
    }
    result, _ = _mcp_post(server_endpoint, payload, session_id)
    if "error" in result:
        raise RuntimeError(f"MCP tool error: {result['error']}")
    return result.get("result", {})

