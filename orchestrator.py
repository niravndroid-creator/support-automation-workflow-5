# Logging is configured by main.py; orchestrator uses a named logger.
logger = logging.getLogger("workflow.orchestrator")

# Structured per-step log — cleared at the start of each run.
_step_logs: list[dict] = []

def get_step_logs() -> list[dict]:
    """Return the accumulated structured step log for the most recent run."""
    return list(_step_logs)

def _log_step(step_name: str, info: str, result: object = None) -> None:
    _step_logs.append({
        "time": datetime.now(timezone.utc).isoformat(),
        "step": step_name,
        "info": info,
        "result": result,
    })

# Azure AI Foundry client — shared across all agent calls
_project_client = AIProjectClient(
    endpoint=PROJECT_ENDPOINT,
    credential=AzureKeyCredential(AZURE_AI_API_KEY),
)

